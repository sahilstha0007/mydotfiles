#!/usr/bin/env bash
# lazygit/lazydocker-palette.sh — regenerate the lazygit + lazydocker themes
# from the shared wallpaper palette (matugen.lua), so the two TUIs follow the
# wallpaper like every other layer instead of freezing on a hardcoded `blue`.
#
# WHY: wezterm, tmux, nvim, kitty, oh-my-posh, herdr, opencode all re-theme
# from matugen.lua on wallpaper change. lazygit/lazydocker were the last two
# pinned to named ANSI colors (`blue`/`bold`), so a purple/green wallpaper
# re-themed the whole cockpit EXCEPT these — breaking the "one palette
# everywhere" invariant. Same treatment as opencode-palette.sh (also a TUI,
# also launch-read, also WCAG-guarded).
#
# lazygit/lazydocker read their config.yml at launch — no live reload, so the
# new colors apply on the next `Ctrl+a g` / `Ctrl+a d` (which is fine: they are
# relaunched constantly). Nothing to signal; just rewrite the file.
#
# Preserves the user's NON-theme settings by templating around the theme block:
# lazygit's diffRenderers/quitOnTopLevelReturn/notARepository/etc and
# lazydocker's reporting/selectedLineBgColor stay exactly as hand-written.
set -euo pipefail

src="$HOME/.config/wezterm/colors/matugen.lua"
lg="$HOME/.config/lazygit/config.yml"
ld="$HOME/.config/lazydocker/config.yml"

# Shared readability rule (WCAG 4.5:1 + lightness repair) — identical to
# tmux/wezterm/nvim/herdr/opencode, so the TUIs cannot drift from the stack.
LEGIBLE_PY="$HOME/.config/wezterm/utils/legible.py"
[ -f "$src" ] || exit 0

get() { sed -nE "s/^[[:space:]]*$1 = \"#([0-9a-fA-F]{6})\".*/\1/p" "$src" | head -1; }

bg=$(get background)
primary=$(get primary)
surface1=$(get surface1)
outline=$(get outline)

# No background token = cannot run the gate honestly (same rule as the other
# palette scripts): leave the last good config in place rather than guessing.
[ -n "$bg" ] || exit 0

# The active border is the wallpaper's primary accent. Guard it so it stays
# readable against the transparent popup background (the terminal shows through,
# so the effective bg is the wallpaper's own background token). Inactive border
# and selected-line use the outline/surface tokens — quiet, not accent.
accent=$(python3 "$LEGIBLE_PY" "#${primary:-bfce7f}" "#$bg" 2>/dev/null | sed 's/^#//') || accent="${primary:-bfce7f}"
muted=$(python3 "$LEGIBLE_PY" "#${outline:-919283}" "#$bg" 2>/dev/null | sed 's/^#//') || muted="${outline:-919283}"
inactive="${surface1:-2a2b23}"

# --- lazygit: rewrite ONLY the gui.theme block, keep everything else. -------
# We regenerate the whole file from the known-good non-theme settings the user
# has, so a wallpaper change can never drop a hand-tuned line. If you add new
# non-theme lazygit settings later, add them here too (or move the theme block
# out and patch in place).
lg_tmp="${lg}.tmp.$$"
cat > "$lg_tmp" <<EOF
git:
  diffRenderers:
    - colorArg: always
      command: delta --dark --paging=never
gui:
  showRandomTip: false
  border: rounded
  theme:
    activeBorderColor:
      - '#$accent'
      - bold
    inactiveBorderColor:
      - '#$muted'
    selectedLineBgColor:
      - '#$inactive'
  sidePanelWidth: 0.33
  expandFocusedSidePanel: true
quitOnTopLevelReturn: true
disableStartupPopups: true
notARepository: quit
EOF
mv "$lg_tmp" "$lg"

# --- lazydocker: same treatment. -------------------------------------------
ld_tmp="${ld}.tmp.$$"
cat > "$ld_tmp" <<EOF
# lazydocker theme — generated by lazygit/lazydocker-palette.sh from the
# wallpaper palette (matugen.lua). Matches ~/.config/lazygit/config.yml
# (rounded border, accent active border) and the tmux popup chrome around it.
gui:
  border: rounded
  theme:
    activeBorderColor:
      - '#$accent'
      - bold
    inactiveBorderColor:
      - '#$muted'
    selectedLineBgColor:
      - reverse
reporting: local
EOF
mv "$ld_tmp" "$ld"

exit 0
