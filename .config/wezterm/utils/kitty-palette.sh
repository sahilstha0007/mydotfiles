#!/bin/sh
# Regenerate kitty's palette (~/.config/kitty/colors-matugen.conf) from the
# same wallpaper that drives wezterm, so the two terminals never disagree.
#
# WHY A SCRIPT AND NOT A matugen TEMPLATE: kitty needs all 16 ANSI slots plus
# fg/bg. matugen.lua carries only 12 colour tokens, and the ANSI array lives in
# wezterm's colors/custom.lua where it is RESOLVED at runtime — after the
# readability guard, after brights are derived from ansi, and with primary
# mapped into ANSI blue so lazygit/fzf borders follow the wallpaper. Reading
# those resolved values (rather than approximating a second mapping from
# matugen tokens) is what makes kitty's colours identical to wezterm's.
#
# ⚠ UNUSED — MANUAL ONLY (state re-verified 2026-10-17)
#
# Nothing calls this script. `sync-wallpaper.sh` deliberately does not invoke
# it (its own comment: "kitty is not in this cascade — it is pure ml4w and
# follows its own matugen config") and no other file in ~/.config references
# it. It is kept because it is the tested way to move kitty ONTO the cascade if
# that is ever wanted — but it must not be run casually.
#
# The paragraph that used to sit here claimed ml4w's `[templates.kitty]` block
# "is removed there". It is NOT removed. It is live at
# ~/.config/matugen/config.toml:7-10, it is the single writer of
# ~/.config/kitty/colors-matugen.conf, it renders from the DESKTOP wallpaper,
# and its post-hook is `pkill -SIGUSR1 kitty`. Checked against the running
# system, not against intent. Anyone trusting the old text would conclude kitty
# follows the dev-stack wallpaper; it does not.
#
# The boundary that actually holds: kitty = ml4w's desktop path, one writer.
# The dev stack = the wezterm cascade, one writer. Running this by hand creates
# a SECOND writer for kitty's file, which ml4w silently overwrites at the next
# desktop wallpaper change. Wiring it into a cascade requires deleting the ml4w
# template block first — do that deliberately, not by accident.
#
# On any failure the previous good file is left in place — kitty keeps working,
# just stale.
set -eu

# Arg 1 overrides the destination (same convention as herdr-palette.sh) so the
# generator can be run against a scratch file in tests without touching the live
# kitty config or signalling the running kitty.
real_out="$HOME/.config/kitty/colors-matugen.conf"
out="${1:-$real_out}"
custom="$HOME/.config/wezterm/colors/custom.lua"
palette="$HOME/.config/wezterm/colors/matugen.lua"
# custom.lua builds its palette path from wezterm.config_dir .. '/colors/matugen.lua',
# so this must be the CONFIG DIR, not the path to custom.lua. Passing the file
# made the lookup miss and silently fall back to stock catppuccin.
cfg_dir="$HOME/.config/wezterm"

[ -f "$custom" ] || exit 0
[ -f "$palette" ] || exit 0

# Resolve wezterm's ACTUAL ansi/brights. custom.lua only needs require('wezterm')
# for config_dir/home_dir, so a stub is enough — no wezterm binary involved, and
# the values come from the same file nvim's read_wezterm_palette() reads.
vals=$(lua - "$custom" "$cfg_dir" "$HOME" <<'LUA' 2>/dev/null || true
local conf, cfg_dir, home = ...
package.preload['wezterm'] = function()
   return { config_dir = cfg_dir, home_dir = home }
end
local ok, cs = pcall(dofile, conf)
if not ok or type(cs) ~= 'table' or not cs.ansi or not cs.brights then os.exit(1) end
local out = {}
for i = 1, 8 do out[#out + 1] = cs.ansi[i] end
for i = 1, 8 do out[#out + 1] = cs.brights[i] end
out[#out + 1] = cs.foreground
out[#out + 1] = cs.background
print(table.concat(out, ' '))
LUA
)

# No lua binary, or custom.lua did not resolve: keep the last good file rather
# than writing a partial palette.
[ -n "$vals" ] || exit 0

set -- $vals
a0=$1 a1=$2 a2=$3 a3=$4 a4=$5 a5=$6 a6=$7 a7=$8
b0=$9 b1=${10} b2=${11} b3=${12} b4=${13} b5=${14} b6=${15} b7=${16}
fg=${17} bg=${18}

cat > "$out.tmp" <<EOF
# Generated by ~/.config/wezterm/utils/kitty-palette.sh from the wallpaper that
# drives wezterm. Do not edit by hand; edit the cascade instead.
#
# Color0 is near-background on purpose: ANSI black is the "recede" slot, the
# same exemption tmux and nvim apply. Every other slot is text a user reads.
foreground            $fg
background            $bg
cursor                $a4
cursor_text_color     $bg
selection_foreground  $a7
selection_background  $a5
url_color             $a4

# --- 8 normal ANSI slots (color0-7) ---
color0  $a0
color1  $a1
color2  $a2
color3  $a3
color4  $a4
color5  $a5
color6  $a6
color7  $a7

# --- 8 bright ANSI slots (color8-15) ---
color8  $b0
color9  $b1
color10 $b2
color11 $b3
color12 $b4
color13 $b5
color14 $b6
color15 $b7
EOF

[ -s "$out.tmp" ] || { rm -f "$out.tmp"; exit 0; }
mv "$out.tmp" "$out"

# Only signal a live kitty when writing its real config; a test destination must
# never reload the user's terminal.
if [ "$out" = "$real_out" ]; then
   # SIGUSR1 = reload config, not a restart. Failure-tolerant on purpose: pkill
   # exits 1 when kitty is not running, and both matugen and the cascade treat
   # ANY stray output as failure.
   #
   # -x is REQUIRED, not a nicety: without it the pattern matches the FULL
   # command line, so `pkill kitty` also signals this very script (and the
   # shell that spawned it) the moment its own path contains "kitty". That
   # killed the generator mid-run and printed a "User defined signal 1"
   # message into the cascade, which the cascade then read as failure. -x
   # matches the process NAME only, so it can only ever hit real kitty.
   pkill -x -SIGUSR1 kitty 2>/dev/null || true
fi
exit 0