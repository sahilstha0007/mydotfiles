#!/usr/bin/env bash
# Re-theme the Atlas vault from the same palette the rest of the stack reads
# (~/.config/wezterm/colors/matugen.lua). Called by sync-wallpaper.sh.
#
# This was the Obsidian half of ~/.config/zed/palette.sh. Zed no longer
# follows the wallpaper (it keeps its own theme), so the vault is the only
# remaining consumer — and the vault is a stack surface, not a Zed one, which
# is why this script lives in the wezterm tree.
#
# Obsidian lists snippets by name in appearance.json, so regenerated CSS shows
# up on next start or after toggling the snippet once.
set -euo pipefail

src="$HOME/.config/wezterm/colors/matugen.lua"
snippet="$HOME/Documents/Notes/Atlas/.obsidian/snippets/matugen.css"

[ -f "$src" ] || exit 0
get() { sed -nE "s/^[[:space:]]*$1 = \"#([0-9a-fA-F]{6})\".*/\1/p" "$src" | head -1; }

# No background token means there is nothing trustworthy to paint with — keep
# the previous snippet rather than write a half palette.
bg=$(get background)
[ -n "$bg" ] || exit 0

# Base vars only. !important because the vault layers 11 other snippets
# (AllinOne, Combos, Notebook Backgrounds) that repaint the same surfaces.
if [ -d "$(dirname "$snippet")" ]; then
  fg=$(get foreground); s0=$(get surface0); s1=$(get surface1); s2=$(get surface2)
  pr=$(get primary); se=$(get secondary); te=$(get tertiary)
  er=$(get error); ol=$(get outline)
  cat > "$snippet" <<CSS
/* Generated by ~/.config/wezterm/utils/obsidian-palette.sh from the wallpaper palette. */
body.theme-dark,
body.theme-light {
  --color-base-00: #$bg !important;
  --color-base-10: #$s0 !important;
  --color-base-20: #$s1 !important;
  --color-base-25: #$s1 !important;
  --color-base-30: #$s2 !important;
  --color-base-35: #$s2 !important;
  --color-base-40: #$ol !important;
  --color-base-50: #$ol !important;
  --color-base-60: #$ol !important;
  --color-base-70: #$ol !important;
  --color-base-100: #$fg !important;

  --text-normal: #$fg !important;
  --text-muted: #$ol !important;
  --text-faint: #$ol !important;
  --text-accent: #$pr !important;
  --text-accent-hover: #$pr !important;

  --interactive-accent: #$pr !important;
  --interactive-accent-hover: #$pr !important;
  --text-selection: #$s2 !important;

  --background-primary: #$bg !important;
  --background-secondary: #$s0 !important;
  --background-modifier-border: #$s2 !important;
  --background-modifier-hover: #$s1 !important;

  --text-error: #$er !important;
  --text-success: #$se !important;
  --text-warning: #$te !important;
}
CSS
fi
